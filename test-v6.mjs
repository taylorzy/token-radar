import assert from 'node:assert/strict';
import {readFileSync, readdirSync} from 'node:fs';
import {join} from 'node:path';
import {createHash} from 'node:crypto';
import engine from './dashboard/00-decision.js';
import {buildDossier} from './vendor/makefun-board.ts';

const [out, baseline] = process.argv.slice(2);
const file = (root,name) => readFileSync(join(root,name));
const json = (root,name) => JSON.parse(file(root,name));
const board = json(out,'board.json').rows, old = json(baseline,'board.json').rows;
const review = json(out,'decision-review.json'), farms = json(out,'farming-economics.json');
const intel = json(out,'model-intelligence.json').rows, ledger = json(out,'protocol-accounting.json').rows;
const decisions = new Map(review.decisions.map(d=>[d.slug,d]));
const near = (a,b) => assert.ok(Math.abs(a-b)<1e-6, a+' differs from '+b);
const {economics,defaults} = engine;
const calc = changes => economics(75578185,{...defaults,...changes});
const base = calc({});
near(base.gross,37.7890925);
near(base.opportunity,1000*0.05*30/365);
near(base.hurdle,8+20+1000*0.05*30/365);
near(base.net,base.gross-base.hurdle);
near(base.hourly,base.net+20);
near(base.payout*base.requiredWeight,base.hurdle);
near(base.requiredPayout*0.25,base.hurdle);
near(base.requiredPpm/1e6*75578185*0.25,base.hurdle);
near(calc({fees:base.feeCeiling}).net,0);
assert.equal(calc({hours:0}).hourly,null);
assert.equal(calc({success:0}).requiredPayout,null);
assert.equal(calc({ppm:0}).requiredWeight,null);
for(const invalid of [{fees:null},{success:101},{capital:-1},{capital:Infinity}]) assert.equal(calc(invalid),null);
near(calc({fees:0}).transaction,0);
near(decisions.get('lofty').base.transaction,63);
assert.equal(board.length,182);
assert.deepEqual(ledger,json(baseline,'protocol-accounting.json').rows);
const values = list => list.map(({farm_steps,...row})=>row);
assert.deepEqual(values(board),values(old));
const changed = board.filter((r,i)=>JSON.stringify(r.farm_steps)!==JSON.stringify(old[i].farm_steps)).map(r=>r.slug);
assert.deepEqual(new Set(changed),new Set(['loopscale-lending','firelight','polymarket-international','mellow-core']));
assert.equal(farms.filter(f=>f.route).length,32);
assert.equal(decisions.size,182);
assert.equal(review.coverage.screened,198);
assert.equal(new Set(review.coverage.excluded).size,16);
assert.equal(review.coverage.exceptions.length,5);
assert.equal(review.validation.rows.length,6);
assert.equal(review.decisions[0].slug,'steakhouse-financial');
assert.equal(decisions.get('sentora-curator').verdict,'Assumption-sensitive');
assert.equal(decisions.get('sentora-curator').sensitivity[0].net.toFixed(2),'-29.08');
const rebuilt = board.map((r,i)=>{
  const farm=farms[i], entry=ledger.find(v=>v.slug===r.slug);
  assert.equal(r.slug,farm.slug);
  assert.equal(r.slug,intel[i].slug);
  assert.equal(r.implied_value_usd,intel[i].models.m71.value);
  assert.ok(r.farm_steps.length>=3 && r.farm_steps.length<=12 && r.farm_steps.every(s=>s.trim().length>=20 && s.trim().length<=600));
  const result=engine.assess(r,intel[i],entry,farm);
  const high=engine.assess(r,intel[i],entry,farm,{...defaults,ppm:1000,success:100});
  if(result.tier>=3) assert.equal(result.verdict,high.verdict);
  if(review.coverage.exceptions.includes(r.slug)) assert.equal(result.tier,5);
  if(!farm.route) assert.ok(result.tier>=3);
  assert.ok(result.sensitivity.every(s=>Number.isFinite(s.net)));
  return result;
});
assert.deepEqual(engine.rankDecisions(rebuilt),review.decisions);
const dossier=json(out,'dossier.json');
const caps={text_max_bytes:65536,screenshots:{max:4,max_bytes:524288},dashboard:{max_files:400,max_bytes:4194304}};
assert.deepEqual(Buffer.from(buildDossier(out,caps)),file(out,'dossier.json'));
assert.ok(file(out,'dossier.json').length<=1572864 && file(out,'board.json').length<=8388608);
assert.equal(dossier.images.length,4);
for(const image of dossier.images){
  const bytes=file(join(out,'screenshots'),image.name);
  assert.equal(bytes.readUInt32BE(0),0x89504e47);
  assert.equal(image.sha256,createHash('sha256').update(bytes).digest('hex'));
  assert.deepEqual(bytes,Buffer.from(image.base64,'base64'));
}
for(const name of ['00-decision.js','00-validation.json','00-workspace.js','00-evidence.txt','00-farm-plan.txt','01-farming-routes.json']){
  const source=file(join(out,'dashboard'),name).toString().trimEnd().replaceAll('\r\n','\n');
  assert.ok(dossier.text.replaceAll('\r\n','\n').includes(source),'Judge excerpt omitted '+name);
}
const dash=join(out,'dashboard');
const bytes=readdirSync(dash).reduce((sum,name)=>sum+file(dash,name).length,0);
assert.ok(bytes<=4194304);
console.log('Passed monetary identities, edge cases, 182 decisions, risk gates, V5 parity, route changes and complete judge-visible decision evidence.');
console.log(JSON.stringify({dashboardBytes:bytes,dossierBytes:file(out,'dossier.json').length,excerptBytes:Buffer.byteLength(dossier.text),screenshots:dossier.images.map(i=>[i.name,file(join(out,'screenshots'),i.name).length])}));
